def _tb_sheet(price_mode, d1, d2, plus):
    """A T-bill sheet: days to maturity, years, and the annual yield (RATE) or the price (PV)."""
    lab = 'תשואה שנתית לפדיון' if price_mode else 'מחיר (אגורות)'
    d = {'A1': 'ערך נקוב (אגורות)', 'A2': lab, 'A4': 'ימים לפדיון', 'A5': 'שנים לפדיון', 'A6': 'מחיר היום (אגורות)' if price_mode else 'תשואה שנתית לפדיון'}
    dd = f'=DATE({d2[0]},{d2[1]},{d2[2]})-DATE({d1[0]},{d1[1]},{d1[2]})' + ('+1' if plus else '')
    s = {'B4': dd, 'B5': '=B4/365', 'B6': '=-PV(B2,B5,0,B1)' if price_mode else '=RATE(B5,0,-B2,B1)'}
    when = 'בבוקר, ולכן ועוד 1' if plus else 'בשער הנעילה, ולכן בלי תוספת'
    steps = [dict(cells={'B4': dd}, note=f'שלב 1, ימים לפדיון: הפרש התאריכים, {when}: {dd}.'),
             dict(cells={'B5': '=B4/365'}, note='שלב 2, שנים: הימים חלקי 365, =B4/365. כך התוצאה תהיה שנתית.'),
             dict(cells={'B6': s['B6']}, note=('שלב 3, המחיר: ' + s['B6'] + '. PV מחזיר מספר שלילי, כי זה מה שמשלמים, ולכן הסימן מינוס לפני הפונקציה. קופון 0, ו-100 בפדיון.') if price_mode else
                  ('שלב 3, התשואה: ' + s['B6'] + '. המחיר נכנס בסימן שלילי, הקופון 0, ובפדיון 100. אותה תוצאה גם ב-=(B1/B2)^(1/B5)-1.'))]
    traps = {'B4': [(dd[:-2] if plus else dd + '+1', 'בדקו מתי נקנה המק״מ: בבוקר מוסיפים 1, בשער הנעילה לא.')], 'B5': [('=B4/360', 'בשנה 365 ימים.')]}
    if price_mode: traps['B6'] = [('=PV(B2,B5,0,B1)', 'הסימן הפוך: PV מחזיר מספר שלילי, כי זה מה שמשלמים. המחיר חיובי: =-PV(B2,B5,0,B1).')]
    else: traps['B6'] = [('=RATE(B5,0,B2,B1)', 'המחיר נכנס בסימן שלילי: =RATE(B5,0,-B2,B1).'), ('=RATE(B4,0,-B2,B1)', 'זו תשואה ליום. מספר התקופות הוא בשנים, B5.')]
    hints = ['ימים לפדיון: =DATE(שנה,חודש,יום) של הפדיון, פחות DATE של יום הקנייה. ' + ('בבוקר: ועוד 1.' if plus else 'בשער הנעילה: בלי תוספת.'), 'שנים: =B4/365.',
             'מחיר: =-PV(B2,B5,0,B1).' if price_mode else 'תשואה: =RATE(B5,0,-B2,B1).']
    fmt = {'B6': 'num2' if price_mode else 'pct2', 'B5': 'num4'}
    if price_mode: fmt['B2'] = 'pct2'
    return d, s, steps, hints, traps, fmt


